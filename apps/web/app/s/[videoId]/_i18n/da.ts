export function fillPlaceholders(
	text: string,
	vars?: Record<string, string | number>,
): string {
	if (!vars) return text;
	return text.replace(/\{(\w+)\}/g, (match, name: string) =>
		name in vars ? String(vars[name]) : match,
	);
}

export function t(
	english: string,
	vars?: Record<string, string | number>,
): string {
	const translated = Object.hasOwn(translations, english)
		? translations[english]
		: undefined;
	return fillPlaceholders(translated ?? english, vars);
}

export function fromNow(date: Date): string {
	return formatDistanceToNow(date, { addSuffix: true, locale: da });
}

export function formatNumber(
	value: number,
	options?: Intl.NumberFormatOptions,
): string {
	return new Intl.NumberFormat(DATE_LOCALE, options).format(value);
}
